"""machine_id parity: the Worker's JS copy (public/consider-core.js) must give the same ids as agent/bench.py.

The fixture is generated by agent/bench.py itself; this test re-checks bench.machine_id against it so a change on
either side shows up here. Run: TMPDIR=<symlink-free dir> python3 -m unittest tests/test_consider_parity.py
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "agent"))
import bench  # noqa: E402

GIB = 2 ** 30


class MachineIdParity(unittest.TestCase):
    def test_fixture_matches_bench(self):
        fixture = json.loads((ROOT / "tests" / "fixtures" / "machine_id_parity.json").read_text())
        self.assertGreaterEqual(len(fixture["cases"]), 6)
        for c in fixture["cases"]:
            with self.subTest(brand=c["brand"], gb=c["memory_gb"]):
                self.assertEqual(bench.machine_id(chip=c["brand"], mem=c["memory_gb"] * GIB), c["machine_id"])


if __name__ == "__main__":
    unittest.main()
